"""
PayAgent AI - an invoicing agent built on the PayPal Invoicing API (sandbox).

Type one sentence ("Invoice Ravi Rs 4000 for logo design, due Friday") and the agent
turns it into a structured invoice (Gemini), asks you to confirm, creates and sends a real
PayPal sandbox invoice, and tracks paid / unpaid status. It can also answer
"who hasn't paid?" and send payment reminders.
"""

import json
import os
import re
import time
from datetime import datetime, timedelta
from pathlib import Path
from typing import List, Optional

import requests
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

load_dotenv()

PAYPAL_CLIENT_ID = os.getenv("PAYPAL_CLIENT_ID", "")
PAYPAL_CLIENT_SECRET = os.getenv("PAYPAL_CLIENT_SECRET", "")
PAYPAL_BASE_URL = os.getenv("PAYPAL_BASE_URL", "https://api-m.sandbox.paypal.com")
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")
GEMINI_MODEL = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
# PayPal invoicing is not reliable for INR in the sandbox, so INR is converted to USD
# at this (approximate, configurable) rate and the original amount is kept in the note.
INR_PER_USD = float(os.getenv("INR_PER_USD", "88"))

PAYPAL_LIVE = bool(PAYPAL_CLIENT_ID and PAYPAL_CLIENT_SECRET)
BASE_DIR = Path(__file__).parent

app = FastAPI(title="PayAgent AI", version="2.0.0")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])

INVOICES: List[dict] = []  # in-memory; re-synced from PayPal after a restart
_synced = {"done": False}


# ----------------------------------------------------------------------------- models
class Item(BaseModel):
    name: str
    quantity: int = Field(1, ge=1)
    unit_amount: float = Field(..., gt=0)


class InvoiceDraft(BaseModel):
    client_name: str
    client_email: Optional[str] = None
    currency: str = "USD"
    due_date: str
    items: List[Item]
    note: Optional[str] = None


class AgentRequest(BaseModel):
    prompt: str


# ----------------------------------------------------------------------------- PayPal
_tok = {"value": "", "exp": 0.0}


def _token() -> str:
    if _tok["value"] and time.time() < _tok["exp"]:
        return _tok["value"]
    r = requests.post(
        f"{PAYPAL_BASE_URL}/v1/oauth2/token",
        auth=(PAYPAL_CLIENT_ID, PAYPAL_CLIENT_SECRET),
        data={"grant_type": "client_credentials"},
        headers={"Accept": "application/json"},
        timeout=20,
    )
    if r.status_code != 200:
        raise HTTPException(502, f"PayPal auth failed: {r.text[:200]}")
    d = r.json()
    _tok.update(value=d["access_token"], exp=time.time() + int(d.get("expires_in", 300)) - 60)
    return _tok["value"]


def pp(method: str, path: str, body: Optional[dict] = None, params: Optional[dict] = None) -> dict:
    r = requests.request(
        method,
        f"{PAYPAL_BASE_URL}{path}",
        json=body,
        params=params,
        headers={"Authorization": f"Bearer {_token()}", "Content-Type": "application/json"},
        timeout=30,
    )
    if r.status_code >= 400:
        raise HTTPException(502, f"PayPal error {r.status_code}: {r.text[:300]}")
    return r.json() if r.content else {}


def normalize_status(s: str) -> str:
    s = (s or "").upper()
    if s in ("PAID", "MARKED_AS_PAID"):
        return "PAID"
    if s in ("CANCELLED", "CANCELED"):
        return "CANCELLED"
    return "UNPAID"


def paypal_amounts(d: InvoiceDraft):
    """Return (currency, [(name, qty, unit_amount)], note) in a currency PayPal accepts."""
    cur = d.currency.upper()
    note = d.note or "Generated by PayAgent AI"
    if cur == "INR":
        items = [(i.name, i.quantity, round(i.unit_amount / INR_PER_USD, 2)) for i in d.items]
        orig = sum(i.quantity * i.unit_amount for i in d.items)
        note += f" | Original amount: INR {orig:,.2f} (converted at {INR_PER_USD:g} INR/USD)"
        return "USD", items, note
    return cur, [(i.name, i.quantity, round(i.unit_amount, 2)) for i in d.items], note


def paypal_create_and_send(d: InvoiceDraft):
    currency, items, note = paypal_amounts(d)
    number = pp("POST", "/v2/invoicing/generate-next-invoice-number")["invoice_number"]
    payload = {
        "detail": {
            "invoice_number": number,
            "currency_code": currency,
            "note": note,
            "payment_term": {"term_type": "DUE_ON_DATE_SPECIFIED", "due_date": d.due_date},
        },
        "primary_recipients": [
            {"billing_info": {"name": {"given_name": d.client_name}, "email_address": d.client_email}}
        ],
        "items": [
            {
                "name": n,
                "quantity": str(q),
                "unit_amount": {"currency_code": currency, "value": f"{a:.2f}"},
            }
            for n, q, a in items
        ],
    }
    created = pp("POST", "/v2/invoicing/invoices", payload)
    inv_id = created["href"].rstrip("/").split("/")[-1]
    # A draft has no payer link. Sending it publishes the invoice (we don't email the recipient).
    pp("POST", f"/v2/invoicing/invoices/{inv_id}/send",
       {"send_to_recipient": False, "send_to_invoicer": False})
    info = pp("GET", f"/v2/invoicing/invoices/{inv_id}")
    link = info.get("detail", {}).get("metadata", {}).get("recipient_view_url", "")
    total = sum(q * a for _, q, a in items)
    return inv_id, link, info.get("status", "SENT"), currency, total


def sync_from_paypal():
    """After a restart (e.g. Render free tier spin-down) rebuild the dashboard from PayPal."""
    _synced["done"] = True
    try:
        data = pp("GET", "/v2/invoicing/invoices",
                  params={"page": 1, "page_size": 50, "total_required": "false"})
    except Exception:
        return
    known = {i["id"] for i in INVOICES}
    for it in data.get("items", []):
        if it.get("id") in known:
            continue
        detail = it.get("detail", {})
        recips = it.get("primary_recipients") or [{}]
        bi = recips[0].get("billing_info", {})
        name = bi.get("name", {}).get("given_name") or bi.get("email_address", "Client")
        amt = it.get("amount", {})
        INVOICES.append({
            "id": it["id"], "client_name": name, "client_email": bi.get("email_address", ""),
            "currency": amt.get("currency_code", detail.get("currency_code", "USD")),
            "total_amount": float(amt.get("value", 0) or 0),
            "paypal_currency": amt.get("currency_code", "USD"),
            "paypal_total": float(amt.get("value", 0) or 0),
            "items": [], "due_date": (detail.get("payment_term") or {}).get("due_date", ""),
            "status": normalize_status(it.get("status")), "created_at": detail.get("invoice_date", ""),
            "payment_link": detail.get("metadata", {}).get("recipient_view_url", ""),
            "mode": "live",
        })


# ----------------------------------------------------------------------------- AI agent
SYSTEM_PROMPT = """You are PayAgent, an invoicing agent for freelancers and small shops.
Today is __TODAY__ (__WEEKDAY__). Convert the user's message into ONLY this JSON:
{
  "intent": "create_invoice" | "list_unpaid" | "send_reminder" | "unknown",
  "invoice": {"client_name": str, "client_email": str or null, "currency": "INR"|"USD"|"EUR"|"GBP",
              "due_date": "YYYY-MM-DD",
              "items": [{"name": str, "quantity": int, "unit_amount": number}],
              "note": str or null} or null,
  "client_name": str or null,
  "reply": one short friendly sentence describing what you understood
}
Rules: resolve relative dates ("Friday", "next week", "in 10 days") to a real YYYY-MM-DD in the future;
default due date is 7 days from today; Rs/rupees/INR symbol means INR; unit_amount is the price of one unit;
"list_unpaid" is for questions like "who hasn't paid"; "send_reminder" is for "remind Ravi" (set client_name)."""


def call_gemini(text: str) -> Optional[dict]:
    now = datetime.now()
    system = SYSTEM_PROMPT.replace("__TODAY__", now.strftime("%Y-%m-%d")).replace(
        "__WEEKDAY__", now.strftime("%A"))
    try:
        r = requests.post(
            f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent",
            params={"key": GEMINI_API_KEY},
            json={
                "system_instruction": {"parts": [{"text": system}]},
                "contents": [{"role": "user", "parts": [{"text": text}]}],
                "generationConfig": {"temperature": 0, "responseMimeType": "application/json"},
            },
            timeout=30,
        )
        r.raise_for_status()
        return json.loads(r.json()["candidates"][0]["content"]["parts"][0]["text"])
    except Exception:
        return None


WEEKDAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]


def heuristic_parse(text: str) -> dict:
    """Offline fallback so the app still works without an AI key (less capable)."""
    low = text.lower()
    if re.search(r"unpaid|owe|outstanding|who hasn|pending", low):
        return {"intent": "list_unpaid", "reply": "Here are your unpaid invoices."}
    m = re.search(r"remind\s+([A-Za-z]+)", text, re.IGNORECASE)
    if m:
        return {"intent": "send_reminder", "client_name": m.group(1),
                "reply": f"Sending a reminder to {m.group(1)}."}

    currency = "USD"
    if "₹" in text or re.search(r"\binr\b|rupee|\brs\b", low):
        currency = "INR"
    elif "€" in text or "eur" in low:
        currency = "EUR"
    elif "£" in text or "gbp" in low:
        currency = "GBP"

    am = re.search(r"([0-9]+(?:,[0-9]{3})*(?:\.[0-9]+)?)", text)
    amount = float(am.group(1).replace(",", "")) if am else 0
    nm = re.search(r"(?:invoice|bill|charge)\s+([A-Za-z]+)", text, re.IGNORECASE)
    client = nm.group(1).capitalize() if nm else "Client"
    fm = re.search(r"\bfor\s+([^,.]+?)(?:,|\s+due|$)", text, re.IGNORECASE)
    desc = fm.group(1).strip().capitalize() if fm else "Professional services"

    today = datetime.now()
    due = today + timedelta(days=7)
    if "tomorrow" in low:
        due = today + timedelta(days=1)
    for idx, day in enumerate(WEEKDAYS):
        if day in low:
            due = today + timedelta(days=((idx - today.weekday()) % 7) or 7)
    if amount <= 0:
        return {"intent": "unknown", "reply": "I couldn't find an amount. Try: Invoice Ravi 4000 for logo design, due Friday."}
    return {
        "intent": "create_invoice",
        "reply": f"Invoice for {client}: {desc}.",
        "invoice": {"client_name": client, "currency": currency, "due_date": due.strftime("%Y-%m-%d"),
                    "items": [{"name": desc, "quantity": 1, "unit_amount": amount}]},
    }


def default_email(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]", "", name.lower()) or "client"
    return f"{slug}@example.com"


def do_remind(inv: dict):
    if PAYPAL_LIVE and inv.get("mode") == "live":
        pp("POST", f"/v2/invoicing/invoices/{inv['id']}/remind",
           {"subject": f"Reminder: invoice {inv['id']}", "note": "Friendly reminder from PayAgent AI."})
    inv["last_reminder"] = datetime.now().isoformat()


# ----------------------------------------------------------------------------- routes
@app.get("/")
def index():
    return FileResponse(BASE_DIR / "static" / "index.html")


@app.get("/api/health")
def health():
    return {"paypal_live": PAYPAL_LIVE, "ai": "gemini" if GEMINI_API_KEY else "fallback"}


@app.post("/api/agent")
def agent(req: AgentRequest):
    text = req.prompt.strip()
    if not text:
        raise HTTPException(400, "Empty prompt")
    result, mode = None, "fallback"
    if GEMINI_API_KEY:
        result = call_gemini(text)
        mode = "gemini" if result else "fallback"
    if not result:
        result = heuristic_parse(text)

    intent = result.get("intent", "unknown")
    out = {"intent": intent, "ai_mode": mode, "reply": result.get("reply", "")}

    if intent == "create_invoice":
        try:
            draft = InvoiceDraft(**(result.get("invoice") or {}))
            draft.currency = draft.currency.upper()
            draft.client_email = draft.client_email or default_email(draft.client_name)
            datetime.strptime(draft.due_date, "%Y-%m-%d")
            out["draft"] = draft.model_dump() if hasattr(draft, "model_dump") else draft.dict()
        except Exception:
            out.update(intent="unknown", reply="I couldn't build a valid invoice from that. Please rephrase.")
    elif intent == "list_unpaid":
        unpaid = [i for i in INVOICES if i["status"] == "UNPAID"]
        out["invoices"] = unpaid
        out["reply"] = f"You have {len(unpaid)} unpaid invoice(s)."
    elif intent == "send_reminder":
        name = (result.get("client_name") or "").lower()
        match = next((i for i in INVOICES if i["status"] == "UNPAID" and name and name in i["client_name"].lower()), None)
        if match:
            do_remind(match)
            out["reply"] = f"Reminder sent to {match['client_name']} for invoice {match['id']}."
        else:
            out["reply"] = "I couldn't find an unpaid invoice for that client."
    return out


@app.post("/api/invoices")
def create_invoice(d: InvoiceDraft):
    d.currency = d.currency.upper()
    d.client_email = d.client_email or default_email(d.client_name)
    original_total = sum(i.quantity * i.unit_amount for i in d.items)
    if PAYPAL_LIVE:
        inv_id, link, status, pp_cur, pp_total = paypal_create_and_send(d)
    else:
        inv_id, link, status, pp_cur, pp_total = f"SIM-{int(time.time())}", "", "SENT", d.currency, original_total
    record = {
        "id": inv_id, "client_name": d.client_name, "client_email": d.client_email,
        "currency": d.currency, "total_amount": original_total,
        "paypal_currency": pp_cur, "paypal_total": pp_total,
        "items": [i.model_dump() if hasattr(i, "model_dump") else i.dict() for i in d.items], "due_date": d.due_date,
        "status": normalize_status(status), "created_at": datetime.now().isoformat(),
        "payment_link": link, "mode": "live" if PAYPAL_LIVE else "simulated",
    }
    INVOICES.insert(0, record)
    return record


@app.get("/api/invoices")
def list_invoices():
    if PAYPAL_LIVE and not _synced["done"] and not INVOICES:
        sync_from_paypal()
    return INVOICES


def _find(invoice_id: str) -> dict:
    inv = next((i for i in INVOICES if i["id"] == invoice_id), None)
    if not inv:
        raise HTTPException(404, "Invoice not found")
    return inv


@app.post("/api/invoices/{invoice_id}/refresh")
def refresh(invoice_id: str):
    """Pull the latest status from PayPal (works after the payer pays via the payment link)."""
    inv = _find(invoice_id)
    if inv["mode"] == "live":
        info = pp("GET", f"/v2/invoicing/invoices/{invoice_id}")
        inv["status"] = normalize_status(info.get("status"))
    return inv


@app.post("/api/invoices/{invoice_id}/mark-paid")
def mark_paid(invoice_id: str):
    """Demo helper: records an offline payment in PayPal so status becomes PAID."""
    inv = _find(invoice_id)
    if inv["mode"] == "live":
        pp("POST", f"/v2/invoicing/invoices/{invoice_id}/payments", {
            "payment_date": datetime.now().strftime("%Y-%m-%d"),
            "method": "OTHER",
            "amount": {"currency_code": inv["paypal_currency"], "value": f"{inv['paypal_total']:.2f}"},
            "note": "Marked paid from PayAgent AI",
        })
        inv["status"] = normalize_status(pp("GET", f"/v2/invoicing/invoices/{invoice_id}").get("status"))
    else:
        inv["status"] = "PAID"
    return inv


@app.post("/api/invoices/{invoice_id}/remind")
def remind(invoice_id: str):
    inv = _find(invoice_id)
    do_remind(inv)
    return inv


